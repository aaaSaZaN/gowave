import { readdirSync, readFileSync, unlinkSync, writeFileSync } from 'node:fs'
import { dirname, join, resolve } from 'node:path'
import postcss from 'postcss'

const root = resolve(import.meta.dirname, '../src')
const check = process.argv.includes('--check')
const stale = []

function localSelector(selector) {
    let result = ''
    for (let index = 0; index < selector.length; index++) {
        if (!selector.startsWith(':global(', index)) {
            result += selector[index]
            continue
        }
        let depth = 1
        index += ':global('.length
        for (; index < selector.length && depth > 0; index++) {
            const character = selector[index]
            if (character === '(') depth++
            if (character === ')') depth--
        }
        index--
    }
    return result
}

function visit(directory) {
    for (const entry of readdirSync(directory, { withFileTypes: true })) {
        const path = join(directory, entry.name)
        if (entry.isDirectory()) {
            visit(path)
            continue
        }
        if (entry.name.endsWith('.module.d.css.ts')) {
            const source = path.replace(/\.d\.css\.ts$/, '.css')
            try {
                readFileSync(source)
            } catch (error) {
                if (error.code !== 'ENOENT') throw error
                if (check) stale.push(path)
                else unlinkSync(path)
            }
            continue
        }
        if (!entry.name.endsWith('.module.css')) continue
        const classes = new Set()
        postcss.parse(readFileSync(path, 'utf8'), { from: path }).walkRules((rule) => {
            const selector = localSelector(rule.selector)
            for (const match of selector.matchAll(/\.([_a-zA-Z][\w-]*)/g)) classes.add(match[1])
        })
        const properties = [...classes].sort().map((name) => {
            const key = /^[a-zA-Z_$][\w$]*$/.test(name) ? name : `'${name}'`
            return `    readonly ${key}: string`
        })
        const declaration = `// Generated by bun run css:types from ${entry.name}.\n// Regenerate after changing CSS class names.\ndeclare const classes: {\n${properties.join('\n')}\n}\nexport default classes\n`
        const output = join(dirname(path), entry.name.replace(/\.css$/, '.d.css.ts'))
        let current = ''
        try {
            current = readFileSync(output, 'utf8')
        } catch (error) {
            if (error.code !== 'ENOENT') throw error
        }
        if (current === declaration) continue
        if (check) stale.push(output)
        else writeFileSync(output, declaration)
    }
}

visit(root)
if (stale.length) {
    process.stderr.write(`CSS types are out of date. Run bun run css:types.\n${stale.join('\n')}\n`)
    process.exitCode = 1
}
