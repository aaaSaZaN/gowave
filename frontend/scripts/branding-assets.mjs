import { execFileSync } from 'node:child_process'
import { createHash } from 'node:crypto'
import { readFileSync, writeFileSync } from 'node:fs'
import { join, resolve } from 'node:path'

const root = resolve(import.meta.dirname, '..')
const artwork = join(root, 'public/favicons/gowave.svg')
const version = createHash('sha256').update(readFileSync(artwork)).digest('hex').slice(0, 12)
const indexPath = join(root, 'index.html')
const index = readFileSync(indexPath, 'utf8').replaceAll('favicons/logo.svg', 'favicons/gowave.svg')

function render(size) {
    return execFileSync('rsvg-convert', [
        '--width',
        String(size),
        '--height',
        String(size),
        artwork
    ])
}

for (const size of [16, 32, 48, 64, 128, 180, 192, 512]) {
    writeFileSync(join(root, `public/favicons/favicon-${size}x${size}.png`), render(size))
}

// The HTML media queries define every supported startup size, including
// older devices that did not have an image in the original asset collection.
const startupLinks = index.matchAll(/<link\s+rel="apple-touch-startup-image"[\s\S]*?\/>/g)
let startupCount = 0
for (const [link] of startupLinks) {
    const width = Number(link.match(/device-width: (\d+)px/)?.[1])
    const height = Number(link.match(/device-height: (\d+)px/)?.[1])
    const ratio = Number(link.match(/device-pixel-ratio: (\d+)/)?.[1])
    const file = link.match(/href="\.\/([^"?]+)/)?.[1]
    if (!width || !height || !ratio || !file) throw new Error(`Invalid startup image: ${link}`)
    const dimensions = link.includes('orientation: landscape')
        ? `${height * ratio}x${width * ratio}`
        : `${width * ratio}x${height * ratio}`
    execFileSync(
        'magick',
        [
            '-size',
            dimensions,
            'xc:#161B23',
            'png:-',
            '-gravity',
            'center',
            '-composite',
            '-strip',
            join(root, 'public', file)
        ],
        { input: render(Math.round(Math.min(width, height) * ratio * 0.22)) }
    )
    startupCount++
}
if (!startupCount) throw new Error('No startup image media queries found')

const assetUrl =
    /\.\/(?:favicons\/[^"?]+\.(?:svg|png)|splash_screens\/[^"?]+\.png)(?:\?v=[^"\s]+)?/g
const versioned = (url) => `${url.split('?')[0]}?v=${version}`
writeFileSync(indexPath, index.replace(assetUrl, versioned))

const manifestPath = join(root, 'public/site.webmanifest')
const manifest = readFileSync(manifestPath, 'utf8')
writeFileSync(manifestPath, manifest.replace(assetUrl, versioned))

// Subscription pages can run on another origin; embed the same artwork so
// their default logo does not depend on the dashboard path or a third party.
const database = resolve(root, '../backend/internal/database')
const configPath = join(database, 'default_subpage_config.json')
const config = JSON.parse(readFileSync(configPath, 'utf8'))
const logoData = `data:image/svg+xml;base64,${readFileSync(artwork).toString('base64')}`
config.brandingSettings.logoUrl = logoData
const configJson = JSON.stringify(config)
if (configJson.includes('`'))
    throw new Error('Subscription config contains a Go raw-string delimiter')
writeFileSync(configPath, configJson)
writeFileSync(
    join(database, 'default_subpage_config_data.go'),
    `// Code generated by bun scripts/branding-assets.mjs from frontend/; DO NOT EDIT.\npackage database\n\nvar DefaultSubpageConfigData = \`${configJson}\`\n`
)
const defaultsPath = join(database, 'default_data.go')
writeFileSync(
    defaultsPath,
    readFileSync(defaultsPath, 'utf8').replace(/("logoUrl":")[^"]*(")/g, `$1${logoData}$2`)
)
process.stdout.write(
    `Generated 8 favicons and ${startupCount} startup images from GoWave artwork\n`
)
